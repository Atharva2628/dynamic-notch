import AppKit
import ImageIO
import SwiftUI

extension ClipboardFeature {
    /// Pure-logic checks: dedupe, limit with pins, skipping, search, persistence (in a
    /// temporary folder that is removed afterwards), image handling.
    static func selfTest(_ check: (Bool, String) -> Void) {
        let fm = FileManager.default
        let dir = fm.temporaryDirectory.appendingPathComponent("dynamicnotch-clipboard-\(UUID().uuidString)", isDirectory: true)
        let images = dir.appendingPathComponent("clipboard-images", isDirectory: true)
        let fileURL = dir.appendingPathComponent("clipboard.json")
        try? fm.createDirectory(at: images, withIntermediateDirectories: true)
        defer { try? fm.removeItem(at: dir) }

        // Dedupe, pins and the limit.
        let store = ClipboardStore(fileURL: fileURL, imagesDirectory: images, limit: 3)
        store.autosave = false
        store.restore([])
        let alpha = store.add(.make(.text, text: "alpha"))
        store.add(.make(.text, text: "beta"))
        let again = store.add(.make(.text, text: "alpha"))
        check(store.items.map(\.text) == ["alpha", "beta"] && again.id == alpha.id,
              "clipboard: copying the same text again moves it to the top, no duplicate")
        store.togglePin(id: alpha.id)
        store.add(.make(.text, text: "gamma"))
        store.add(.make(.text, text: "alpha"))
        check(store.items.first?.id == alpha.id && store.item(id: alpha.id)?.pinned == true,
              "clipboard: a repeat keeps its pin")
        for text in ["d", "e", "f", "g"] { store.add(.make(.text, text: text)) }
        check(store.items.filter { !$0.pinned }.map(\.text) == ["g", "f", "e"] && store.item(id: alpha.id) != nil,
              "clipboard: the limit keeps the newest unpinned items plus every pin")

        let imageName = "dropped.png"
        fm.createFile(atPath: images.appendingPathComponent(imageName).path, contents: Data([1]))
        var picture = ClipboardItem(kind: .image, text: "Image 1 × 1", fingerprint: "picture")
        picture.imageFile = imageName
        store.add(picture)
        for text in ["h", "i", "j"] { store.add(.make(.text, text: text)) }
        store.drainIO()
        check(store.item(id: picture.id) == nil && !fm.fileExists(atPath: images.appendingPathComponent(imageName).path),
              "clipboard: a dropped image's file is deleted")
        store.togglePin(id: alpha.id)
        check(store.items.count == 3 && !store.items.contains { $0.pinned }, "clipboard: unpinning trims back to the limit")

        // Skipping and choosing.
        let skip = ClipboardWatcher.skipReason
        check(skip(["public.utf8-plain-text", "org.nspasteboard.ConcealedType"], []) != nil
              && skip(["public.utf8-plain-text", "com.agilebits.onepassword"], []) != nil
              && skip(["org.nspasteboard.TransientType"], []) != nil
              && skip(["org.nspasteboard.AutoGeneratedType"], []) != nil
              && skip(["de.petermaurer.TransientPasteboardType"], []) != nil
              && skip(["public.utf8-plain-text", "com.typeit4me.clipping"], []) != nil
              && skip(["public.utf8-plain-text", "Pasteboard generator type"], []) != nil
              && skip(["public.utf8-plain-text", "net.antelle.keeweb"], []) != nil,
              "clipboard: concealed, transient, generated and password-manager copies are skipped")
        check(skip(["public.utf8-plain-text"], ["com.bitwarden.desktop"]) != nil
              && skip(["public.utf8-plain-text"], ["com.1password.1password"]) != nil
              && skip(["public.utf8-plain-text", "public.html"], ["com.apple.Safari"]) == nil,
              "clipboard: copies made in a password manager are skipped, others kept")
        check(skip(["public.utf8-plain-text"], ["com.apple.Passwords", "com.apple.Safari"]) != nil,
              "clipboard: a copy is skipped when a password manager was in front at the last check, though Safari is now")
        let tooLong = ClipboardWatcher.isTooLong
        let limit = ClipboardWatcher.maxTextBytes
        check(!tooLong("short") && !tooLong(String(repeating: "a", count: limit))
              && tooLong(String(repeating: "a", count: limit + 1))
              && tooLong(String(repeating: "\u{E9}", count: limit / 2 + 1)) && !tooLong(String(repeating: "\u{E9}", count: limit / 2)),
              "clipboard: the text size limit counts UTF-8 bytes")
        let choose = ClipboardWatcher.choose
        check(choose(["public.file-url", "public.tiff", "public.utf8-plain-text"], "notes.md") == .files
              && choose(["public.png", "public.utf8-plain-text"], "Q3 revenue") == .text
              && choose(["public.tiff", "public.utf8-plain-text"], "https://example.com/a.png") == .image
              && choose(["public.png"], nil) == .image
              && choose(["public.utf8-plain-text"], " \n") == nil,
              "clipboard: files beat icons, a cell's text beats its picture, blank text is ignored")
        let link = ClipboardWatcher.link
        check(link(" https://github.com/x?y=1 \n") != nil && link("see https://x.com") == nil
              && link("example.com") == nil && link("javascript:alert(1)") == nil,
              "clipboard: links are single web addresses")
        func kind(_ text: String) -> ClipboardKind? {
            ClipboardWatcher.makeItem(.text(text), source: nil, imagesDirectory: images)?.kind
        }
        check(ClipboardRGBA.parse(hex: "#FF9F0A")?.hex == "#FF9F0A" && ClipboardRGBA.parse(hex: "#f80")?.hex == "#FF8800"
              && ClipboardRGBA.parse(hex: "#GG0000") == nil
              && kind("#FF9F0A") == .color && kind("https://a.example") == .link && kind("123456") == .text,
              "clipboard: copied text becomes a color (only with a #), a link or plain text")
        check(kind("#123") == .text && kind("#333") == .color && kind("#f80") == .color,
              "clipboard: an issue number like #123 stays text")
        check(ClipboardRGBA(red: .nan, green: 2, blue: -1).hex == "#00FF00",
              "clipboard: out-of-range color values are clamped, not a crash")

        // Search.
        var resume = ClipboardItem.make(.files, text: "/tmp/Résumé.pdf")
        resume.paths = ["/tmp/Résumé.pdf"]
        var other = ClipboardItem.make(.text, text: "other", source: "Safari")
        other.pinned = true
        let sample = [ClipboardItem.make(.text, text: "Hello,\nWorld"), resume, other]
        check(ClipboardStore.filter(sample, query: "world HELLO", pinnedOnly: false).count == 1
              && ClipboardStore.filter(sample, query: "hello moon", pinnedOnly: false).isEmpty,
              "clipboard: search needs every word, ignoring case")
        check(ClipboardStore.filter(sample, query: "resume", pinnedOnly: false).first?.kind == .files
              && ClipboardStore.filter(sample, query: "safari", pinnedOnly: false).first?.text == "other",
              "clipboard: search finds file names (ignoring accents) and the source app")
        check(ClipboardStore.filter(sample, query: "", pinnedOnly: true).map(\.text) == ["other"]
              && ClipboardStore.filter(sample, query: " ", pinnedOnly: false).count == 3,
              "clipboard: the pinned filter, and an empty search shows everything")

        // Persistence.
        var swatch = ClipboardItem.make(.color, text: "#FF9F0A", source: "Figma")
        swatch.color = ClipboardRGBA.parse(hex: "#FF9F0A")
        swatch.thumbnail = Data([1, 2, 3])
        store.add(swatch)
        store.togglePin(id: swatch.id)
        store.flush()
        let reloaded = ClipboardStore(fileURL: fileURL, imagesDirectory: images, limit: 3)
        reloaded.autosave = false
        reloaded.restore(ClipboardStore.loadSaved(fileURL: fileURL, imagesDirectory: images))
        let pairs = zip(store.items, reloaded.items)
        check(reloaded.items.count == store.items.count
              && pairs.allSatisfy { $0.id == $1.id && $0.text == $1.text && $0.pinned == $1.pinned && $0.kind == $1.kind
                  && $0.color == $1.color && $0.thumbnail == $1.thumbnail && abs($0.copiedAt.timeIntervalSince($1.copiedAt)) < 1 },
              "clipboard: history survives a save and load, in order, with pins")

        let good = String(decoding: (try? JSONEncoder.notch.encode(ClipboardItem.make(.text, text: "kept"))) ?? Data(), as: UTF8.self)
        try? Data(#"{"version": 1, "items": [42, "x", {"bogus": 1}, \#(good)]}"#.utf8).write(to: fileURL)
        let orphan = images.appendingPathComponent("orphan.png")
        fm.createFile(atPath: orphan.path, contents: Data([1]))
        check(ClipboardStore.loadSaved(fileURL: fileURL, imagesDirectory: images).map(\.text) == ["kept"]
              && !fm.fileExists(atPath: orphan.path),
              "clipboard: a broken entry doesn't cost the rest of the history, and stray images are swept")
        try? Data("not json".utf8).write(to: fileURL)
        fm.createFile(atPath: orphan.path, contents: Data([1]))
        let afterBroken = ClipboardStore.loadSaved(fileURL: fileURL, imagesDirectory: images)
        let broken = ClipboardStore.brokenURLs(fileURL: fileURL, imagesDirectory: images)
        check(afterBroken.isEmpty && fm.fileExists(atPath: broken.file.path)
              && fm.fileExists(atPath: broken.images.appendingPathComponent("orphan.png").path)
              && !fm.fileExists(atPath: fileURL.path) && !fm.fileExists(atPath: images.path),
              "clipboard: an unreadable file is set aside with its images, which aren't swept")
        let clearing = ClipboardStore(fileURL: fileURL, imagesDirectory: images, limit: 3)
        clearing.autosave = false
        clearing.restore([])
        clearing.clearUnpinned()
        clearing.drainIO()
        check(!fm.fileExists(atPath: broken.file.path) && !fm.fileExists(atPath: broken.images.path),
              "clipboard: Clear History also deletes a set-aside history, even with nothing to clear")

        // Images.
        if let png = testImage(width: 400, height: 200).flatMap(ClipboardWatcher.encodePNG),
           let item = ClipboardWatcher.makeItem(.image(png), source: nil, imagesDirectory: images),
           let file = item.imageFile, let thumb = item.thumbnail,
           let source = CGImageSourceCreateWithData(thumb as CFData, nil),
           let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any] {
            let w = props[kCGImagePropertyPixelWidth] as? Int ?? 0
            let h = props[kCGImagePropertyPixelHeight] as? Int ?? 0
            check(item.text == "Image 400 × 200" && fm.fileExists(atPath: images.appendingPathComponent(file).path)
                  && max(w, h) <= 160 && w > 0,
                  "clipboard: an image is saved as PNG, with a small thumbnail")
            let repeated = ClipboardWatcher.makeItem(.image(png), source: nil, imagesDirectory: images, known: [item.fingerprint])
            check(repeated?.fingerprint == item.fingerprint && repeated?.imageFile == nil,
                  "clipboard: an image already in the history isn't written again")
            let image = ClipboardWatcher.imageData(at: images.appendingPathComponent(file))
            let written = image.flatMap { ClipboardWatcher.pasteboardItems(for: item, image: $0)?.first }
            let promised = written?.types.contains(.tiff) == true
            if let image, let written { image.pasteboard(nil, item: written, provideDataForType: .tiff) }
            check(image?.png == png && written?.data(forType: .png) == png && promised
                  && written?.data(forType: .tiff)?.isEmpty == false
                  && ClipboardWatcher.pasteboardItems(for: item, image: nil) == nil,
                  "clipboard: an image copies back as PNG with TIFF made on request, and not at all without its file")
        } else {
            check(false, "clipboard: an image is saved as PNG, with a small thumbnail")
        }
        if let jpeg = testImage(width: 400, height: 200).flatMap({ rotatedJPEG($0, orientation: 6) }),
           let processed = ClipboardWatcher.processImage(jpeg),
           let source = CGImageSourceCreateWithData(processed.png as CFData, nil),
           let decoded = CGImageSourceCreateImageAtIndex(source, 0, nil) {
            check(processed.width == 200 && processed.height == 400 && decoded.width == 200 && decoded.height == 400,
                  "clipboard: a photo's EXIF orientation is applied to the saved PNG and its size")
        } else {
            check(false, "clipboard: a photo's EXIF orientation is applied to the saved PNG and its size")
        }
        let fileItems = ClipboardWatcher.pasteboardItems(for: resume, image: nil)
        let swatchItem = ClipboardWatcher.pasteboardItems(for: swatch, image: nil)?.first
        check(fileItems?.count == 1 && fileItems?.first?.string(forType: .fileURL) == URL(fileURLWithPath: "/tmp/Résumé.pdf").absoluteString
              && swatchItem?.string(forType: .string) == "#FF9F0A" && swatchItem?.types.contains(.color) == true,
              "clipboard: files copy back as file URLs, colors as a color plus their text")
        var tampered = ClipboardItem.make(.image, text: "Image")
        tampered.imageFile = "../config.json"
        check(store.imageURL(for: tampered) == nil, "clipboard: a saved image name can't point outside its folder")

        // Display helpers.
        let now = Date()
        check(ClipboardFormat.relative(now.addingTimeInterval(-30), now: now) == "now"
              && ClipboardFormat.relative(now.addingTimeInterval(-300), now: now) == "5m"
              && ClipboardFormat.relative(now.addingTimeInterval(-3 * 3600), now: now) == "3h"
              && ClipboardFormat.relative(now.addingTimeInterval(-2 * 86_400), now: now) == "2d"
              && ClipboardItem.make(.text, text: "  a\n\n  b\tc ").previewLine == "a b c",
              "clipboard: relative times, and text on one line in the list")
        let ids = [UUID(), UUID(), UUID()]
        check(ClipboardViewState.moved(from: ids[0], by: -1, in: ids) == ids[0]
              && ClipboardViewState.moved(from: ids[1], by: 5, in: ids) == ids[2]
              && ClipboardViewState.moved(from: nil, by: 1, in: ids) == ids[1],
              "clipboard: arrow keys stop at the ends")
        store.drainIO()
    }

    /// The tab and the Home card with sample entries, on a fixed clock.
    static func snapshotViews() -> [(name: String, view: AnyView)] {
        let now = Date(timeIntervalSinceReferenceDate: 783_000_000)
        let scratch = FileManager.default.temporaryDirectory.appendingPathComponent("dynamicnotch-clipboard-snapshot")
        let store = ClipboardStore(fileURL: scratch.appendingPathComponent("clipboard.json"),
                                   imagesDirectory: scratch.appendingPathComponent("images", isDirectory: true), limit: 40)
        store.autosave = false
        let items = sampleItems(now: now)
        store.restore(items)

        let linkState = ClipboardViewState()
        linkState.selectedID = items[1].id
        let imageState = ClipboardViewState()
        imageState.selectedID = items[3].id
        let searchState = ClipboardViewState()
        searchState.query = "deck"

        func tab(_ state: ClipboardViewState) -> AnyView {
            AnyView(ClipboardTabView(store: store, state: state, actions: ClipboardActions(), snapshotDate: now)
                .frame(width: 758, height: 186)
                .background(Color.black)
                .environment(\.colorScheme, .dark))
        }
        let card = ClipboardHomeCard(store: store, state: ClipboardViewState(), actions: ClipboardActions())
            .frame(width: 145, height: 186)
            .background(NotchStyle.card, in: RoundedRectangle(cornerRadius: NotchStyle.cornerRadius, style: .continuous))
            .background(Color.black)
            .environment(\.colorScheme, .dark)
        return [
            ("clipboard-tab", tab(linkState)),
            ("clipboard-tab-image", tab(imageState)),
            ("clipboard-tab-search", tab(searchState)),
            ("clipboard-card", AnyView(card)),
        ]
    }

    private static func sampleItems(now: Date) -> [ClipboardItem] {
        func ago(_ minutes: Double) -> Date { now.addingTimeInterval(-minutes * 60) }
        var text = ClipboardItem.make(.text, text: "Let's move the design review to 3pm, I'll send the Zoom link after lunch.",
                                      source: "Messages")
        text.copiedAt = ago(0.2)
        var link = ClipboardItem.make(.link, text: "https://github.com/migueldeicaza/SwiftTerm/blob/main/README.md", source: "Safari")
        link.copiedAt = ago(4)
        var color = ClipboardItem.make(.color, text: "#FF9F0A", source: "Figma")
        color.color = ClipboardRGBA.parse(hex: "#FF9F0A")
        color.copiedAt = ago(12)
        var image = ClipboardItem.make(.image, text: "Image 1470 × 956", source: "Screenshot")
        image.thumbnail = testImage(width: 160, height: 104).flatMap(ClipboardWatcher.encodePNG)
        image.copiedAt = ago(25)
        var files = ClipboardItem.make(.files, text: "", source: "Finder")
        files.paths = ["/Users/you/Documents/Notes.md", "/Users/you/Documents/Pitch deck.pdf"]
        files.text = files.paths!.joined(separator: "\n")
        files.copiedAt = ago(70)
        var command = ClipboardItem.make(.text, text: "swift build -c release --scratch-path /tmp/dn-build\n./scripts/install.sh",
                                         source: "Terminal")
        command.pinned = true
        command.copiedAt = ago(180)
        var note = ClipboardItem.make(.text, text: "Ship clipboard and shelf by Oct 30; switch on Nov 1.", source: "Notes")
        note.pinned = true
        note.copiedAt = ago(3 * 1440)
        return [text, link, color, image, files, command, note]
    }

    /// `image` as a JPEG whose EXIF says to turn it (6: a quarter turn clockwise, as a
    /// phone held upright writes it).
    private static func rotatedJPEG(_ image: CGImage, orientation: Int) -> Data? {
        let out = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(out, "public.jpeg" as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(dest, image, [kCGImagePropertyOrientation: orientation] as CFDictionary)
        return CGImageDestinationFinalize(dest) ? out as Data : nil
    }

    /// A gradient with a light "window" on it, drawn without any screen.
    private static func testImage(width: Int, height: Int) -> CGImage? {
        guard let space = CGColorSpace(name: CGColorSpace.sRGB),
              let ctx = CGContext(data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: 0,
                                  space: space, bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue),
              let gradient = CGGradient(colorsSpace: space,
                                        colors: [CGColor(srgbRed: 0.18, green: 0.32, blue: 0.86, alpha: 1),
                                                 CGColor(srgbRed: 0.88, green: 0.36, blue: 0.62, alpha: 1)] as CFArray,
                                        locations: [0, 1]) else { return nil }
        ctx.drawLinearGradient(gradient, start: .zero, end: CGPoint(x: width, y: height), options: [])
        ctx.setFillColor(CGColor(gray: 1, alpha: 0.85))
        ctx.fill(CGRect(x: width / 6, y: height / 5, width: width * 2 / 3, height: height * 3 / 5))
        return ctx.makeImage()
    }
}
