import AppKit
import ImageIO
import UniformTypeIdentifiers

/// Whether macOS lets this app read what other apps copy (Privacy & Security, Paste
/// from Other Apps). History records copies only while it's `allowed`.
enum ClipboardAccess: Equatable {
    case allowed, asks, denied

    init(_ behavior: NSPasteboard.AccessBehavior) {
        switch behavior {
        case .default, .alwaysAllow: self = .allowed   // never asked yet, or always allowed
        case .ask: self = .asks
        case .alwaysDeny: self = .denied
        @unknown default: self = .asks                 // don't read what we can't tell is allowed
        }
    }
}

/// What was read off the pasteboard, before the slow part (hashing, PNG, thumbnail).
enum ClipboardCapture: Sendable {
    case text(String)
    case files([String])
    case color(ClipboardRGBA)
    case image(Data)
}

/// Polls the general pasteboard's change count every 0.5 s and reads each new copy on a
/// background queue, so a slow provider (another app rendering on request, Universal
/// Clipboard fetching from a phone) never stalls the notch. Reads only while macOS allows
/// it without asking. Skips what password managers mark as concealed or transient,
/// anything copied while a password manager was in front, and our own writes.
@MainActor
final class ClipboardWatcher {
    /// Markers from nspasteboard.org and password managers: never record these.
    nonisolated static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
        ownType.rawValue,
    ]

    /// 1Password, Passwords, Bitwarden, KeePassXC, LastPass, Keychain Access. Add an ID only
    /// after checking it in the installed app's Info.plist (CFBundleIdentifier). Copies made
    /// by a manager's browser extension (Proton Pass, 1Password in a browser) come from the
    /// browser, so only the pasteboard markers above can catch those.
    nonisolated static let passwordManagers: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "com.agilebits.onepassword4", "com.apple.Passwords", "com.bitwarden.desktop",
        "org.keepassxc.keepassxc", "com.lastpass.LastPass", "com.lastpass.lastpassmacdesktop",
        "com.apple.keychainaccess",
    ]

    /// Put on everything we write, so our own copies are never recorded twice.
    nonisolated static let ownType = NSPasteboard.PasteboardType("local.dynamicnotch.clipboard")
    /// The bundle ID of the app that made a copy, when it says (nspasteboard.org).
    nonisolated static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")

    /// In order of preference: compressed formats first, uncompressed TIFF last.
    nonisolated static let imageTypes = ["public.png", "public.jpeg", "public.heic", "com.compuserve.gif", "public.tiff"]
    nonisolated static let maxTextBytes = 1_000_000
    nonisolated static let maxImageBytes = 60_000_000

    /// A new copy and the name of the app it was made in.
    var onCapture: ((ClipboardCapture, String?) -> Void)?
    /// Called with the pasteboard access setting at start, after each copy and on `checkAccess()`.
    var onAccessChange: ((ClipboardAccess) -> Void)?
    var paused = false

    private let pasteboard: NSPasteboard
    /// Reads run here. Main doesn't touch the pasteboard while one is in flight (ticks are
    /// skipped), and writes wait on this queue, so the two never use it at once.
    private let readQueue = DispatchQueue(label: "local.dynamicnotch.clipboard.pasteboard", qos: .userInitiated)
    private var lastChangeCount = 0
    private var timer: Timer?
    private var readInFlight = false
    /// Counts our own writes, so a read that started before one is dropped.
    private var writes = 0
    /// Every app that was in front since the last check: the copy was made in one of them.
    private var candidateSources: Set<String> = []
    private var activationObserver: NSObjectProtocol?
    private var access: ClipboardAccess?
    /// The last image written, which makes its TIFF if an app asks for one.
    private var lastImage: ClipboardImageData?

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    /// Starts from what's on the pasteboard now, without recording it.
    func start() {
        lastChangeCount = pasteboard.changeCount
        candidateSources = Self.frontmostBundleID().map { [$0] } ?? []
        reportAccess()
        activationObserver = NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main
        ) { [weak self] note in
            let id = (note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication)?.bundleIdentifier
            MainActor.assumeIsolated { self?.appActivated(id) }
        }
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        if let activationObserver { NSWorkspace.shared.notificationCenter.removeObserver(activationObserver) }
        activationObserver = nil
    }

    /// Reads the access setting again (the notch or the tab opened), so the "paused" state
    /// clears once it's set to Always Allow, before the next copy.
    func checkAccess() {
        guard !readInFlight else { return }   // the read reports it when it's done
        reportAccess()
    }

    /// Call right after writing to the pasteboard, so that copy isn't recorded again.
    func ignoreCurrentContents() {
        writes += 1
        let pasteboard = pasteboard
        lastChangeCount = readQueue.sync { pasteboard.changeCount }
    }

    /// Puts an entry back on the pasteboard and marks that copy as ours. Waits for a read in
    /// flight. An image entry needs its `image` (from `imageData(at:)`). Returns false if it can't.
    func write(_ item: ClipboardItem, image: ClipboardImageData?) -> Bool {
        let pasteboard = pasteboard
        guard readQueue.sync(execute: { Self.write(item, image: image, to: pasteboard) }) else { return false }
        lastImage = image
        ignoreCurrentContents()
        return true
    }

    private func reportAccess() {
        let current = ClipboardAccess(pasteboard.accessBehavior)
        access = current
        onAccessChange?(current)
    }

    /// Another app came to the front. Coming back from System Settings is also when the
    /// access setting may have changed.
    private func appActivated(_ bundleID: String?) {
        if let bundleID { candidateSources.insert(bundleID) }
        if access != .allowed { checkAccess() }
    }

    private static func frontmostBundleID() -> String? {
        NSWorkspace.shared.frontmostApplication?.bundleIdentifier
    }

    private func poll() {
        guard !readInFlight else { return }
        // The next check looks at apps in front from now on.
        defer { candidateSources = Self.frontmostBundleID().map { [$0] } ?? [] }
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        lastImage = nil                       // another app owns the pasteboard now
        reportAccess()
        // Read only when macOS allows it without asking. In .ask every read is a system
        // alert whose Allow lasts one read, so reading would alert on every copy anywhere.
        // In .default (never asked yet) the first read may alert once; macOS then moves
        // the setting to .ask by itself, which the report after the read picks up.
        guard access == .allowed, !paused else { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        let front = NSWorkspace.shared.frontmostApplication
        var sources = candidateSources
        if let id = front?.bundleIdentifier { sources.insert(id) }
        if let reason = Self.skipReason(types: types, sourceBundleIDs: sources) {
            ClipboardLog.logger.info("skipped a copy: \(reason, privacy: .public)")
            return
        }
        readInFlight = true
        // Only the read queue uses the pasteboard until the read is back (see `readQueue`).
        nonisolated(unsafe) let pasteboard = pasteboard
        let writes = writes, name = front?.localizedName
        readQueue.async { [weak self] in
            let capture = Self.capture(types, changeCount: count, from: pasteboard)
            DispatchQueue.main.async { [weak self] in
                MainActor.assumeIsolated { self?.finishRead(capture, writes: writes, source: name) }
            }
        }
    }

    /// Back on main. Drops the copy if we were stopped or paused, or wrote to the pasteboard
    /// meanwhile (the user copied an entry back).
    private func finishRead(_ capture: ClipboardCapture?, writes: Int, source: String?) {
        readInFlight = false
        guard timer != nil else { return }
        reportAccess()
        guard let capture, writes == self.writes, !paused else { return }
        onCapture?(capture, source)
    }

    /// Why a copy must not be recorded, or nil to record it. `sourceBundleIDs`: every app
    /// that was in front between the last check and this one; the copy was made in one of
    /// them. That may also skip a copy made right after leaving a password manager.
    nonisolated static func skipReason(types: Set<String>, sourceBundleIDs: Set<String>) -> String? {
        if let marker = types.first(where: skippedTypes.contains) { return "marked \(marker)" }
        if let id = sourceBundleIDs.first(where: passwordManagers.contains) { return "copied in \(id)" }
        return nil
    }

    /// Whether text is over `maxTextBytes` of UTF-8, decided before anything walks it: a
    /// bridged string's UTF-16 length is O(1), and UTF-8 never takes fewer bytes than that
    /// many code units, nor more than 3 per unit.
    nonisolated static func isTooLong(_ text: String) -> Bool {
        let units = (text as NSString).length
        if units > maxTextBytes { return true }
        if units * 3 <= maxTextBytes { return false }
        return text.utf8.count > maxTextBytes
    }

    // MARK: Reading

    enum Source: Equatable { case files, image, color, text }

    /// Which representation to keep. Files win (Finder also puts an icon and the name on the
    /// pasteboard). An image wins over text only when the text is empty or just its address
    /// (a browser's Copy Image); spreadsheet cells and slides put a picture beside their
    /// text, and the text is what you want back.
    nonisolated static func choose(types: Set<String>, string: String?) -> Source? {
        if types.contains(NSPasteboard.PasteboardType.fileURL.rawValue) { return .files }
        let text = string.flatMap { $0.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ? nil : $0 }
        let hasImage = imageTypes.contains(where: types.contains)
        if hasImage && (text == nil || link(from: text!) != nil) { return .image }
        if types.contains(NSPasteboard.PasteboardType.color.rawValue) { return .color }
        return text == nil ? nil : .text
    }

    /// A single http(s), ftp or mailto address with nothing around it.
    nonisolated static func link(from text: String) -> URL? {
        let s = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !s.isEmpty, s.count < 4000, !s.contains(where: \.isWhitespace),
              let url = URL(string: s), let scheme = url.scheme?.lowercased() else { return nil }
        switch scheme {
        case "http", "https", "ftp": return (url.host?.isEmpty == false) ? url : nil
        case "mailto": return s.count > 7 ? url : nil
        default: return nil
        }
    }

    /// Reads a copy, on the read queue. Nil when it's skipped, unreadable or too large, or
    /// when the pasteboard changed while it was read: a password manager may have put a
    /// concealed item over it, which the next check then sees with its own types.
    nonisolated static func capture(_ types: Set<String>, changeCount: Int, from pasteboard: NSPasteboard) -> ClipboardCapture? {
        if types.contains(sourceType.rawValue), let id = pasteboard.string(forType: sourceType),
           let reason = skipReason(types: [], sourceBundleIDs: [id]) {
            ClipboardLog.logger.info("skipped a copy: \(reason, privacy: .public)")
            return nil
        }
        guard let capture = read(types, from: pasteboard),
              pasteboard.changeCount == changeCount,
              Set((pasteboard.types ?? []).map(\.rawValue)) == types else { return nil }
        return capture
    }

    nonisolated static func read(_ types: Set<String>, from pasteboard: NSPasteboard) -> ClipboardCapture? {
        if types.contains(NSPasteboard.PasteboardType.fileURL.rawValue),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return .files(urls.map(\.path))
        }
        let string = pasteboard.string(forType: .string) ?? richText(types, from: pasteboard)
        // Too long to keep: checked before anything walks the text (choosing trims it).
        if let string, isTooLong(string) {
            ClipboardLog.logger.info("skipped \((string as NSString).length) characters of text")
            return nil
        }
        switch choose(types: types.subtracting([NSPasteboard.PasteboardType.fileURL.rawValue]), string: string) {
        case .image:
            guard let type = imageTypes.first(where: types.contains),
                  let data = pasteboard.data(forType: NSPasteboard.PasteboardType(type)) else { return nil }
            guard data.count <= maxImageBytes else {
                ClipboardLog.logger.info("skipped an image of \(data.count) bytes")
                return nil
            }
            return .image(data)
        case .color:
            guard let c = NSColor(from: pasteboard)?.usingColorSpace(.sRGB) else { return nil }
            return .color(ClipboardRGBA(red: Double(c.redComponent), green: Double(c.greenComponent),
                                        blue: Double(c.blueComponent), alpha: Double(c.alphaComponent)))
        case .text:
            return string.map { .text($0) }
        case .files, nil:
            return nil
        }
    }

    /// Rich text with no plain text beside it, as plain text. Not parsed when it's larger
    /// than text we'd keep (RTFD carries its pictures).
    nonisolated static func richText(_ types: Set<String>, from pasteboard: NSPasteboard) -> String? {
        for type in [NSPasteboard.PasteboardType.rtf, .rtfd] where types.contains(type.rawValue) {
            guard let data = pasteboard.data(forType: type) else { continue }
            guard data.count <= maxTextBytes else {
                ClipboardLog.logger.info("skipped \(data.count) bytes of rich text")
                return nil
            }
            let text = type == .rtf ? NSAttributedString(rtf: data, documentAttributes: nil)
                                    : NSAttributedString(rtfd: data, documentAttributes: nil)
            return text?.string
        }
        return nil
    }

    // MARK: Making entries

    /// Turns a capture into a history entry. Runs on the store's io queue: images are
    /// hashed, saved as PNG into `imagesDirectory` and get a thumbnail. An image whose
    /// fingerprint is in `known` isn't written again; the store moves the old entry up.
    nonisolated static func makeItem(_ capture: ClipboardCapture, source: String?, imagesDirectory: URL,
                                     known: Set<String> = []) -> ClipboardItem? {
        switch capture {
        case .text(let text):
            if link(from: text) != nil {
                let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
                return .make(.link, text: trimmed, source: source)
            }
            if let rgba = ClipboardRGBA.parse(hex: text), !ClipboardRGBA.isIssueNumber(text) {
                var item = ClipboardItem.make(.color, text: text.trimmingCharacters(in: .whitespacesAndNewlines), source: source)
                item.color = rgba
                item.fingerprint = ClipboardItem.fingerprint(.color, Data(rgba.hex.utf8))
                return item
            }
            return .make(.text, text: text, source: source)
        case .files(let paths):
            var item = ClipboardItem.make(.files, text: paths.joined(separator: "\n"), source: source)
            item.paths = paths
            return item
        case .color(let rgba):
            var item = ClipboardItem.make(.color, text: rgba.hex, source: source)
            item.color = rgba
            item.fingerprint = ClipboardItem.fingerprint(.color, Data(rgba.hex.utf8))
            return item
        case .image(let data):
            let fingerprint = ClipboardItem.fingerprint(.image, data)
            let id = UUID()
            var item = ClipboardItem(id: id, kind: .image, text: "Image", source: source, fingerprint: fingerprint)
            if known.contains(fingerprint) { return item }
            guard let processed = processImage(data) else { return nil }
            item.text = "Image \(processed.width) × \(processed.height)"
            item.thumbnail = processed.thumbnail
            let name = "\(id.uuidString).png"
            do {
                try FileManager.default.createDirectory(at: imagesDirectory, withIntermediateDirectories: true)
                try processed.png.write(to: imagesDirectory.appendingPathComponent(name), options: .atomic)
                item.imageFile = name
            } catch {
                ClipboardLog.logger.error("could not save an image: \(error.localizedDescription, privacy: .public)")
                return nil
            }
            return item
        }
    }

    /// The image as PNG (as-is when it already is one), upright, its pixel size, and a
    /// thumbnail at most `thumbnailSize` pixels on its longer side.
    nonisolated static func processImage(_ data: Data, thumbnailSize: Int = 160)
        -> (png: Data, thumbnail: Data?, width: Int, height: Int)? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil), CGImageSourceGetCount(source) > 0 else { return nil }
        let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any]
        let orientation = props?[kCGImagePropertyOrientation] as? Int ?? 1
        var width = props?[kCGImagePropertyPixelWidth] as? Int ?? 0
        var height = props?[kCGImagePropertyPixelHeight] as? Int ?? 0
        let png: Data
        if (CGImageSourceGetType(source) as String?) == UTType.png.identifier, orientation == 1, width > 0, height > 0 {
            png = data                                   // no need to decode it
        } else {
            // The PNG carries no EXIF/TIFF orientation, so apply it while decoding; a full-size
            // "thumbnail" is the decoder's way to do that.
            let image: CGImage? = orientation == 1
                ? CGImageSourceCreateImageAtIndex(source, 0, nil)
                : CGImageSourceCreateThumbnailAtIndex(source, 0, [
                    kCGImageSourceCreateThumbnailFromImageAlways: true,
                    kCGImageSourceCreateThumbnailWithTransform: true,
                    kCGImageSourceShouldCacheImmediately: true,
                ] as CFDictionary)
            guard let image, let encoded = encodePNG(image) else { return nil }
            png = encoded
            width = image.width
            height = image.height
        }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: thumbnailSize,
        ]
        let thumbnail = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary).flatMap(encodePNG)
        return (png, thumbnail, width, height)
    }

    /// A file's image at most `maxPixels` on its longer side, for the preview.
    nonisolated static func downsample(_ url: URL, maxPixels: Int) -> CGImage? {
        guard let source = CGImageSourceCreateWithURL(url as CFURL, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixels,
        ]
        return CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary)
    }

    nonisolated static func encodePNG(_ image: CGImage) -> Data? { encode(image, as: .png) }

    nonisolated static func encode(_ image: CGImage, as type: UTType) -> Data? {
        let out = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(out, type.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(dest, image, nil)
        return CGImageDestinationFinalize(dest) ? out as Data : nil
    }

    // MARK: Writing

    /// An image entry's file, ready for the pasteboard. Reads the file, so call it off the
    /// main thread.
    nonisolated static func imageData(at url: URL) -> ClipboardImageData? {
        guard let png = try? Data(contentsOf: url), !png.isEmpty,
              let source = CGImageSourceCreateWithData(png as CFData, nil),
              CGImageSourceGetCount(source) > 0 else { return nil }
        return ClipboardImageData(png: png)
    }

    /// Puts an entry on `pasteboard`. An image entry needs its `image` (from `imageData(at:)`).
    /// Returns false if it can't.
    nonisolated static func write(_ item: ClipboardItem, image: ClipboardImageData?, to pasteboard: NSPasteboard) -> Bool {
        guard let items = pasteboardItems(for: item, image: image), let first = items.first else { return false }
        first.setString(Bundle.main.bundleIdentifier ?? "local.dynamicnotch", forType: sourceType)
        first.setData(Data(), forType: ownType)
        pasteboard.clearContents()
        return pasteboard.writeObjects(items)
    }

    /// The pasteboard items for an entry: one per file, otherwise one. An image goes on as
    /// PNG, with a TIFF promised for apps that only read that.
    nonisolated static func pasteboardItems(for item: ClipboardItem, image: ClipboardImageData?) -> [NSPasteboardItem]? {
        let one = NSPasteboardItem()
        switch item.kind {
        case .text:
            one.setString(item.text, forType: .string)
        case .link:
            one.setString(item.text, forType: .string)
            one.setString(item.text, forType: .URL)
        case .color:
            if let rgba = item.color ?? ClipboardRGBA.parse(hex: item.text),
               let plist = rgba.nsColor.pasteboardPropertyList(forType: .color) {
                if let data = plist as? Data { one.setData(data, forType: .color) } else { one.setPropertyList(plist, forType: .color) }
            }
            one.setString(item.text, forType: .string)
        case .files:
            let items = (item.paths ?? []).map { path -> NSPasteboardItem in
                let file = NSPasteboardItem()
                file.setString(URL(fileURLWithPath: path).absoluteString, forType: .fileURL)
                return file
            }
            return items.isEmpty ? nil : items
        case .image:
            guard let image else { return nil }
            one.setData(image.png, forType: .png)
            one.setDataProvider(image, forTypes: [.tiff])
        }
        return [one]
    }
}

/// An image entry's PNG for the pasteboard. An app that only reads TIFF gets one made when
/// it asks, so copying back doesn't wait on a conversion that's rarely needed. The writer
/// keeps the last one alive while it may still be asked.
final class ClipboardImageData: NSObject, NSPasteboardItemDataProvider, Sendable {
    let png: Data

    init(png: Data) { self.png = png }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        guard type == .tiff, let source = CGImageSourceCreateWithData(png as CFData, nil),
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil),
              let tiff = ClipboardWatcher.encode(image, as: .tiff) else { return }
        item.setData(tiff, forType: type)
    }
}
